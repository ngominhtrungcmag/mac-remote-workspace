#!/usr/bin/env bash
# SEC-T08: dependency + license inventory -> docs/implementation/SBOM.md. Offline.
# Sources: Package.resolved, .build/checkouts/*/LICENSE* (if resolved), scripts/build-freerdp-macos.sh.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
RESOLVED="$ROOT/Package.resolved"
CHECKOUTS="$ROOT/.build/checkouts"
OUT="${1:-$ROOT/docs/implementation/SBOM.md}"
BUILD="$ROOT/scripts/build-freerdp-macos.sh"
frdp="$(sed -n 's/^FREERDP_VERSION="\([^"]*\)"$/\1/p' "$BUILD")"
ossl="$(sed -n 's/^OPENSSL_VERSION="\([^"]*\)"$/\1/p' "$BUILD")"

# Classify the license file of a checkout dir by characteristic text.
detect() {
  local f t
  f="$(ls "$1"/LICENSE* "$1"/LICENCE* "$1"/COPYING* 2>/dev/null | head -1 || true)"
  [ -n "$f" ] || { echo "unknown (no checkout)"; return; }
  t="$(tr -s '[:space:]' ' ' < "$f")"
  case "$t" in
    *"Apache License"*"Version 2.0"*) echo "Apache-2.0" ;;
    *"Permission is hereby granted, free of charge"*) echo "MIT" ;;
    *"Redistribution and use in source and binary forms"*) echo "BSD (verify)" ;;
    *) echo "unrecognized ($(basename "$f"))" ;;
  esac
}

pins="$(/usr/bin/python3 -I -c '
import json,sys
for p in json.load(open(sys.argv[1]))["pins"]:
    s=p["state"]
    print("\t".join([p["identity"],p["location"],s.get("version",s.get("branch","-")),s["revision"]]))
' "$RESOLVED")"

{
  echo "# SBOM (macOS native app)"
  echo
  echo 'Generated by `scripts/sbom-macos.sh` (SEC-T08). Do not edit by hand. No network access used.'
  echo
  echo "## Swift Package Manager pins"
  echo
  echo "| Name | URL | Version | Revision | License |"
  echo "|---|---|---|---|---|"
  while IFS=$'\t' read -r id url ver rev; do
    lic="unknown (no checkout)"
    for d in "$CHECKOUTS"/*; do
      [ -d "$d" ] || continue
      if [ "$(basename "$d" | tr '[:upper:]' '[:lower:]')" = "$id" ]; then lic="$(detect "$d")"; fi
    done
    echo "| $id | $url | $ver | \`$rev\` | $lic |"
  done <<< "$pins"
  echo
  echo "## Vendored native binaries"
  echo
  echo "| Name | Version | Source | License |"
  echo "|---|---|---|---|"
  echo "| FreeRDP (xcframework) | ${frdp:-unknown} | https://github.com/FreeRDP/FreeRDP | Apache-2.0 (verify) |"
  echo "| OpenSSL (static, built for FreeRDP) | ${ossl:-unknown} | https://github.com/openssl/openssl | Apache-2.0 (verify) |"
  echo
  echo "Transitive native codecs inside FreeRDP are not enumerated here. Advisory scanning is a manual step (docs/11-build-release-runbook.md)."
} > "$OUT"
echo "wrote $OUT"
